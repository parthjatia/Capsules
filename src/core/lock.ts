// .capsules/capsules.lock (C7.2, C7.3, C7.4): read, compute, update, write and compare.
import { capsuleHash, nodeHash } from "./hash.js";
import { address, type Capsule } from "./model.js";
import { targetOf } from "./resolve.js";
import { msg, type Diagnostic } from "../report/messages.js";

export const LOCK_FILE = ".capsules/capsules.lock";
export const LOCK_HEADER = "# capsules.lock v1. Generated by `capsules lock`. Do not edit by hand.";

export interface LinkRecord {
  from: string;
  type: string;
  to: string;
  /** Hash of the target when the link was pinned. */
  hash: string;
}

export interface Lock {
  capsules: Map<string, string>;
  nodes: Map<string, { type: string; hash: string }>;
  /** Keyed by `${from} ${type} ${to}`. */
  links: Map<string, LinkRecord>;
  /** Keyed by the prompt node address. */
  files: Map<string, { path: string; blob: string }>;
}

export const linkKey = (from: string, type: string, to: string) => `${from} ${type} ${to}`;

export function emptyLock(): Lock {
  return { capsules: new Map(), nodes: new Map(), links: new Map(), files: new Map() };
}

// --- Reading and writing ----------------------------------------------------------------

const HASH = /^[0-9a-f]{12}$/;
const BLOB = /^[0-9a-f]{40}([0-9a-f]{24})?$/; // SHA-1 or SHA-256 object ids

export function parseLock(text: string): { lock: Lock; diagnostics: Diagnostic[] } {
  const lock = emptyLock();
  const diagnostics: Diagnostic[] = [];
  text
    .replace(/\r\n?/g, "\n")
    .split("\n")
    .forEach((raw, i) => {
      const line = raw.trim();
      if (!line || line.startsWith("#")) return;
      const t = line.split(" ");
      const bad = () => diagnostics.push(msg.E026({ file: LOCK_FILE, line: i + 1 }, raw));
      switch (t[0]) {
        case "capsule":
          if (t.length !== 3 || !HASH.test(t[2]!)) return bad();
          lock.capsules.set(t[1]!, t[2]!);
          return;
        case "node":
          if (t.length !== 4 || !HASH.test(t[3]!)) return bad();
          lock.nodes.set(t[1]!, { type: t[2]!, hash: t[3]! });
          return;
        case "link":
          if (t.length !== 5 || !HASH.test(t[4]!)) return bad();
          lock.links.set(linkKey(t[1]!, t[2]!, t[3]!), {
            from: t[1]!,
            type: t[2]!,
            to: t[3]!,
            hash: t[4]!,
          });
          return;
        case "file": {
          // file <address> <path, may contain spaces> <blob>
          const blob = t[t.length - 1]!;
          if (t.length < 4 || !BLOB.test(blob)) return bad();
          lock.files.set(t[1]!, { path: t.slice(2, -1).join(" "), blob });
          return;
        }
        default:
          return bad();
      }
    });
  return { lock, diagnostics };
}

const byCodeUnits = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

/** Line-based, sorted by kind then lexically, LF, trailing newline (C7.2). */
export function serializeLock(lock: Lock): string {
  const sorted = (lines: string[]) => lines.sort(byCodeUnits);
  const lines = [
    LOCK_HEADER,
    ...sorted([...lock.capsules].map(([id, h]) => `capsule ${id} ${h}`)),
    ...sorted([...lock.nodes].map(([a, n]) => `node ${a} ${n.type} ${n.hash}`)),
    ...sorted([...lock.links.values()].map((l) => `link ${l.from} ${l.type} ${l.to} ${l.hash}`)),
    ...sorted([...lock.files].map(([a, f]) => `file ${a} ${f.path} ${f.blob}`)),
  ];
  return lines.join("\n") + "\n";
}

// --- Current state ------------------------------------------------------------------------

/**
 * The lock as it would be if every link were pinned right now.
 * `blobs` maps prompt file paths to their Git blob hash (missing files are absent).
 */
export function computeCurrent(capsules: Capsule[], blobs: Map<string, string>): Lock {
  const cur = emptyLock();
  for (const c of capsules) {
    if (c.front && c.frontText !== null) cur.capsules.set(c.id, capsuleHash(c.frontText));
    for (const n of c.nodes)
      cur.nodes.set(address(c.id, n.id), { type: n.type, hash: nodeHash(n) });
  }
  for (const c of capsules) {
    for (const n of c.nodes) {
      const from = address(c.id, n.id);
      for (const l of n.links) {
        const to = targetOf(l.ref, c.id);
        const target = cur.nodes.get(to);
        if (!target) continue; // broken link: reported as E003, nothing to pin
        cur.links.set(linkKey(from, l.type, to), { from, type: l.type, to, hash: target.hash });
      }
      if (n.type === "prompt") {
        const path = n.fields.find((f) => f.key === "file")?.value;
        const blob = path ? blobs.get(path) : undefined;
        if (path && blob) cur.files.set(from, { path, blob });
      }
    }
  }
  return cur;
}

export interface UpdateOptions {
  /** `capsules refresh <address>`: re-pin links FROM this node. */
  refreshFrom?: string;
  /** `capsules relock --cosmetic <address>`: re-pin links TO this node. */
  relockTo?: string;
}

/**
 * C7.3. Capsule, node and file records follow the current state. New links are pinned to
 * the current target hash. Existing links keep their pin unless refresh/relock names them.
 * `capsules lock` alone never re-pins an existing link (B12).
 */
export function updateLock(old: Lock | null, current: Lock, opts: UpdateOptions = {}): Lock {
  const next = emptyLock();
  next.capsules = new Map(current.capsules);
  next.nodes = new Map(current.nodes);
  next.files = new Map(current.files);
  for (const [key, cur] of current.links) {
    const prev = old?.links.get(key);
    const repin = cur.from === opts.refreshFrom || cur.to === opts.relockTo;
    next.links.set(key, prev && !repin ? { ...cur, hash: prev.hash } : cur);
  }
  return next;
}

// --- Comparing ----------------------------------------------------------------------------

export interface LockChange {
  kind: "capsule" | "node" | "link" | "file";
  key: string;
  change: "added" | "removed" | "changed";
}

/** What `capsules lock` would change in the record set (E010). Pins of existing links don't count. */
export function lockChanges(onDisk: Lock, current: Lock): LockChange[] {
  const out: LockChange[] = [];
  const cmpMaps = <V>(
    kind: LockChange["kind"],
    a: Map<string, V>,
    b: Map<string, V>,
    same: (x: V, y: V) => boolean,
  ) => {
    for (const [k, v] of b) {
      const old = a.get(k);
      if (old === undefined) out.push({ kind, key: k, change: "added" });
      else if (!same(old, v)) out.push({ kind, key: k, change: "changed" });
    }
    for (const k of a.keys()) if (!b.has(k)) out.push({ kind, key: k, change: "removed" });
  };
  cmpMaps("capsule", onDisk.capsules, current.capsules, (x, y) => x === y);
  cmpMaps("node", onDisk.nodes, current.nodes, (x, y) => x.hash === y.hash && x.type === y.type);
  cmpMaps("link", onDisk.links, current.links, () => true);
  cmpMaps("file", onDisk.files, current.files, (x, y) => x.blob === y.blob && x.path === y.path);
  const order = { capsule: 0, node: 1, link: 2, file: 3 };
  return out.sort((a, b) => order[a.kind] - order[b.kind] || byCodeUnits(a.key, b.key));
}

export interface StaleLink extends LinkRecord {
  current: string;
}

/** C7.4: links whose pinned hash differs from the target's current hash (W104). */
export function staleLinks(onDisk: Lock, current: Lock): StaleLink[] {
  const out: StaleLink[] = [];
  for (const l of onDisk.links.values()) {
    if (!current.links.has(linkKey(l.from, l.type, l.to))) continue; // link removed: lock is out of date instead
    const now = current.nodes.get(l.to)?.hash;
    if (now && now !== l.hash) out.push({ ...l, current: now });
  }
  return out.sort((a, b) =>
    byCodeUnits(linkKey(a.from, a.type, a.to), linkKey(b.from, b.type, b.to)),
  );
}

export interface StalePrompt {
  address: string;
  path: string;
  locked: string;
  current: string;
}

/** C7.4: prompt files whose blob changed since they were locked (W110). */
export function stalePrompts(onDisk: Lock, current: Lock): StalePrompt[] {
  const out: StalePrompt[] = [];
  for (const [a, f] of onDisk.files) {
    const now = current.files.get(a);
    if (now && now.path === f.path && now.blob !== f.blob)
      out.push({ address: a, path: f.path, locked: f.blob, current: now.blob });
  }
  return out.sort((a, b) => byCodeUnits(a.address, b.address));
}
