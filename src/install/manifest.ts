// What `capsules init` installed, so `remove` can undo exactly that (C1, B5, D-026).
// Shared files go in the committed .capsules/installed.json. Machine-only changes (the
// hooks in .claude/settings.local.json, the .git/info/exclude line, the Git hook) go in
// .capsules/_cache/installed-local.json: they differ per machine and hold absolute paths.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const MANIFEST = ".capsules/installed.json";
export const LOCAL_MANIFEST = ".capsules/_cache/installed-local.json";

export interface Manifest {
  format: "0.1";
  /** Files init created from templates, with their Git blob hash at install time. */
  files: { path: string; blob: string }[];
  /** Folders init created (removed again only if empty). */
  dirs: string[];
  /** Agent rule files are generated by `capsules compile`; these say which tools. */
  generated: string[];
  /** AGENTS.md: init added the managed block; `created` if the file didn't exist. */
  agentsMd: { created: boolean } | null;
  /** init created .capsules/ itself (only `remove --all` deletes it). */
  createdCapsules: boolean;
}

export interface LocalManifest {
  format: "0.1";
  /** Settings files we merged hooks into, with their exact bytes before (null: we created it). */
  settings: { path: string; before: string | null }[];
  /** Lines we added to files outside the project, with the file's bytes before. */
  lines: { file: string; line: string; before: string | null }[];
  /** A Git hook file we created. */
  gitHooks: string[];
}

export const emptyManifest = (): Manifest => ({
  format: "0.1",
  files: [],
  dirs: [],
  generated: [],
  agentsMd: null,
  createdCapsules: false,
});
export const emptyLocal = (): LocalManifest => ({
  format: "0.1",
  settings: [],
  lines: [],
  gitHooks: [],
});

function readJson<T>(path: string): T | null {
  try {
    return existsSync(path) ? (JSON.parse(readFileSync(path, "utf8")) as T) : null;
  } catch {
    return null;
  }
}

export const readManifest = (root: string) =>
  readJson<Manifest>(join(root, ...MANIFEST.split("/")));
export const readLocal = (root: string) =>
  readJson<LocalManifest>(join(root, ...LOCAL_MANIFEST.split("/")));

export function writeJsonFile(path: string, value: unknown): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, JSON.stringify(value, null, 2) + "\n");
}

/** Git's blob hash of some text, without running git. */
export function blobHash(text: string | Buffer): string {
  const body = typeof text === "string" ? Buffer.from(text, "utf8") : text;
  return createHash("sha1")
    .update(Buffer.concat([Buffer.from(`blob ${body.length}\0`), body]))
    .digest("hex");
}

/** The templates/ folder shipped with capsules, found from this module's location. */
export function templatesDir(): string {
  let dir = dirname(fileURLToPath(import.meta.url));
  for (;;) {
    if (existsSync(join(dir, "templates", "claude"))) return join(dir, "templates");
    const up = dirname(dir);
    if (up === dir) throw new Error("capsules can't find its templates/ folder");
    dir = up;
  }
}

export function template(rel: string): string {
  return readFileSync(join(templatesDir(), ...rel.split("/")), "utf8").replace(/\r\n?/g, "\n");
}

/** The capsules CLI that is running now, as an absolute path with `/` separators. */
export function cliPath(): string {
  const here = dirname(fileURLToPath(import.meta.url));
  // Bundled: this code is in dist/, next to cli.js. From source (tests): src/install/.
  const candidates = [join(here, "cli.js"), join(here, "..", "..", "dist", "cli.js")];
  const found = candidates.find((c) => existsSync(c)) ?? process.argv[1] ?? "capsules";
  return found.split("\\").join("/");
}
