// `capsules remove` (C15): undo exactly what `init` recorded. Leaves .capsules/ unless --all.
import { existsSync, readdirSync, readFileSync, rmdirSync, rmSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { agentsBlock } from "../compile/paths.js";
import { generatedOnDisk } from "../compile/compile.js";
import { toPosix } from "../core/project.js";
import { HOOK_MARKER, SETTINGS_LOCAL, type Step } from "./init.js";
import { blobHash, LOCAL_MANIFEST, MANIFEST, readLocal, readManifest } from "./manifest.js";
import { hasOurHooks, unmergeHooks } from "./settings-merge.js";

export interface RemovePlan {
  installed: boolean;
  steps: Step[];
  apply: () => void;
}

const read = (p: string) => (existsSync(p) ? readFileSync(p, "utf8") : null);

export function planRemove(root: string, opts: { all?: boolean }): RemovePlan {
  const abs = (p: string) => join(root, ...p.split("/"));
  const m = readManifest(root);
  const l = readLocal(root);
  const steps: Step[] = [];
  const acts: (() => void)[] = [];
  const del = (p: string, why: string, absPath = abs(p)) => {
    if (!existsSync(absPath)) return;
    steps.push({ path: p, change: "delete", why });
    acts.push(() => rmSync(absPath, { force: true }));
  };

  for (const f of m?.files ?? []) {
    const text = existsSync(abs(f.path)) ? readFileSync(abs(f.path)) : null;
    if (text === null) continue;
    del(
      f.path,
      blobHash(text) === f.blob
        ? "installed by capsules init"
        : "installed by capsules init (you changed it since)",
    );
  }
  for (const p of generatedOnDisk(root)) del(p, "generated by capsules compile");

  // The managed AGENTS.md block.
  const agents = read(abs("AGENTS.md"));
  const block = agents === null ? null : agentsBlock(agents);
  if (agents !== null && block !== null) {
    const rest = agents
      .replace(/\r\n?/g, "\n")
      .replace(block, "")
      .replace(/\n{2,}$/, "\n")
      .replace(/^\n+$/, "");
    const created = m?.agentsMd?.created === true;
    if (created && rest.trim() === "") del("AGENTS.md", "it only held the capsules block");
    else {
      steps.push({
        path: "AGENTS.md",
        change: "update",
        why: "take out the capsules block; your text stays",
      });
      acts.push(() => writeFileSync(abs("AGENTS.md"), rest));
    }
  }

  // Hooks in Claude Code settings: from the local record, and any other copy of ours.
  const settings = new Map((l?.settings ?? []).map((s) => [s.path, s.before]));
  for (const p of [SETTINGS_LOCAL, ".claude/settings.json"])
    if (!settings.has(p) && hasOurHooks(read(abs(p)))) settings.set(p, null);
  for (const [p, before] of settings) {
    const now = read(abs(p));
    if (now === null || !hasOurHooks(now)) continue;
    const next = unmergeHooks(now, p, before);
    if (next === null) del(p, "it only held the capsules hooks");
    else {
      steps.push({
        path: p,
        change: "update",
        why: "take out the capsules hooks; your settings stay",
      });
      acts.push(() => writeFileSync(abs(p), next));
    }
  }

  // Lines added outside the project (.git/info/exclude) and the Git hook.
  for (const line of l?.lines ?? []) {
    const now = read(line.file);
    if (now === null || !now.split("\n").includes(line.line)) continue;
    const shown = toPosix(relative(root, line.file));
    steps.push({ path: shown, change: "update", why: `take out "${line.line}"` });
    acts.push(() => {
      const expected =
        (line.before ?? "") +
        (line.before && !line.before.endsWith("\n") ? "\n" : "") +
        line.line +
        "\n";
      if (now === expected && line.before !== null) writeFileSync(line.file, line.before);
      else
        writeFileSync(
          line.file,
          now
            .split("\n")
            .filter((x) => x !== line.line)
            .join("\n"),
        );
    });
  }
  for (const h of l?.gitHooks ?? []) {
    if ((read(h) ?? "").includes(HOOK_MARKER))
      del(toPosix(relative(root, h)), "the commit-msg hook capsules added", h);
  }

  if (opts.all) {
    if (existsSync(abs(".capsules"))) {
      steps.push({
        path: ".capsules/",
        change: "delete",
        why: "every capsule, the lockfile and settings (--all)",
      });
      acts.push(() => rmSync(abs(".capsules"), { recursive: true, force: true }));
    }
  } else {
    del(MANIFEST, "the install record");
    del(LOCAL_MANIFEST, "the per-machine install record");
  }

  // Folders init created, deepest first, if nothing else is left in them.
  const dirs = [...(m?.dirs ?? [])].sort((a, b) => b.split("/").length - a.split("/").length);
  acts.push(() => {
    for (const d of dirs) {
      const p = abs(d);
      if (existsSync(p) && readdirSync(p).length === 0) rmdirSync(p);
    }
  });

  return { installed: Boolean(m || l), steps, apply: () => acts.forEach((a) => a()) };
}
