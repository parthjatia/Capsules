// M4a end to end: compiled agent files (C10) and E011.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { cleanup, demoHistory, run } from "./helpers.js";

afterAll(cleanup);

const read = (dir: string, p: string) => readFileSync(join(dir, ...p.split("/")), "utf8");
const MARKER = "<!-- Generated by capsules from .capsules/. Do not edit. Run: capsules compile -->";

function setAgents(dir: string, agents: string) {
  const p = join(dir, ".capsules", "config.yaml");
  writeFileSync(
    p,
    read(dir, ".capsules/config.yaml").replace(/^agents: .*$/m, `agents: ${agents}`),
  );
}

describe("capsules compile", () => {
  it("writes path-scoped Claude Code rules with front matter first, then the marker", () => {
    const dir = demoHistory();
    const r = run(dir, "compile");
    expect(r.status).toBe(0);
    expect(r.stdout).toContain("create  .claude/rules/capsules-billing.invoices.md");
    const inv = read(dir, ".claude/rules/capsules-billing.invoices.md");
    expect(inv.startsWith(`---\npaths:\n  - "src/billing/invoices/**"\n`)).toBe(true);
    expect(inv).toContain(`---\n${MARKER}\n`);
    // C10 order: intents, rules (own, inherited, concerns), examples, context, decisions, permissions.
    const order = [
      "## What this part is for",
      "billing.invoices#C1",
      "Also inherited from `billing`",
      "Also inherited from `root`",
      "Also from the `payments` concern",
      "## Examples",
      "## Context",
      "## Decisions",
      "Rejected: own ledger",
      "## What you may and must not edit",
    ].map((s) => inv.indexOf(s));
    expect(order.every((i) => i >= 0)).toBe(true);
    expect([...order].sort((a, b) => a - b)).toEqual(order);
    // Transclusions are resolved; the superseded decision is left out.
    expect(inv).not.toContain("{{");
    expect(inv).not.toContain("billing.invoices#D3");
    // The overview has no paths, so it is always loaded.
    expect(read(dir, ".claude/rules/capsules-overview.md").startsWith(MARKER)).toBe(true);
    // root covers nothing in the demo, so it gets no per-capsule file.
    expect(existsSync(join(dir, ".claude", "rules", "capsules-root.md"))).toBe(false);
  });

  it("is deterministic: a second run writes nothing and --check passes", () => {
    const dir = demoHistory();
    run(dir, "compile");
    const before = read(dir, ".claude/rules/capsules-web.md");
    const again = run(dir, "compile");
    expect(again.stdout).toContain("already up to date");
    expect(read(dir, ".claude/rules/capsules-web.md")).toBe(before);
    expect(run(dir, "compile", "--check").status).toBe(0);
  });

  it("--dry-run writes nothing", () => {
    const dir = demoHistory();
    const r = run(dir, "compile", "--dry-run");
    expect(r.stdout).toContain("Would change");
    expect(existsSync(join(dir, ".claude", "rules"))).toBe(false);
  });

  it("reports E011 in --check and in capsules check once installed, and fixes it on compile", () => {
    const dir = demoHistory();
    // Not installed yet: no E011.
    expect(run(dir, "check", "--no-run", "--base", "HEAD").stdout).not.toContain("E011");
    run(dir, "compile");
    const p = join(dir, ".capsules", "web.md");
    writeFileSync(
      p,
      read(dir, ".capsules/web.md").replace("## intent I1\n", "## intent I1\nAlso fast. "),
    );
    const c = run(dir, "compile", "--check");
    expect(c.status).toBe(1);
    expect(c.stdout).toContain("E011");
    expect(c.stdout).toContain(".claude/rules/capsules-web.md is out of date");
    expect(run(dir, "check", "--no-run", "--base", "HEAD").stdout).toContain("E011");
    run(dir, "compile");
    expect(run(dir, "compile", "--check").status).toBe(0);
  });

  it("writes Cursor .mdc rules with a comma-separated globs string when cursor is enabled", () => {
    const dir = demoHistory();
    setAgents(dir, "[claude-code, cursor]");
    run(dir, "compile");
    const mdc = read(dir, ".cursor/rules/capsules-billing.invoices.mdc");
    expect(mdc).toContain(
      "globs: src/billing/invoices/**,tests/invoices/**,prompts/invoice-agent.md\nalwaysApply: false\n---\n",
    );
    expect(read(dir, ".cursor/rules/capsules-overview.mdc")).toContain("alwaysApply: true");
  });

  it("deletes rule files of capsules that no longer exist, or of agents switched off", () => {
    const dir = demoHistory();
    setAgents(dir, "[claude-code, cursor]");
    run(dir, "compile");
    setAgents(dir, "[claude-code]");
    const r = run(dir, "compile");
    expect(r.stdout).toContain("delete  .cursor/rules/capsules-web.mdc");
    expect(existsSync(join(dir, ".cursor", "rules", "capsules-web.mdc"))).toBe(false);
  });

  it("manages only its own block in AGENTS.md and keeps the user's text", () => {
    const dir = demoHistory();
    setAgents(dir, "[agents-md]");
    writeFileSync(join(dir, "AGENTS.md"), "# My agents file\n\nUse pnpm.\n");
    run(dir, "compile");
    const first = read(dir, "AGENTS.md");
    expect(first.startsWith("# My agents file\n\nUse pnpm.\n\n<!-- capsules:begin -->")).toBe(true);
    expect(first.trimEnd().endsWith("<!-- capsules:end -->")).toBe(true);
    expect(first).toContain("capsules explain <file>");
    writeFileSync(join(dir, "AGENTS.md"), first + "\nMore of my notes.\n");
    expect(run(dir, "compile", "--check").status).toBe(0);
    expect(existsSync(join(dir, ".claude", "rules"))).toBe(false);
  });

  it("refuses to compile capsules with errors", () => {
    const dir = demoHistory();
    writeFileSync(join(dir, ".capsules", "web.md"), "no front matter\n");
    const r = run(dir, "compile");
    expect(r.status).toBe(1);
    expect(r.stderr).toContain("nothing written");
  });
});
